"""Scenario configuration (replaces the Run/Location/Manag/Soil sheets).

Every field below carries the `iCrop.vba` line that reads the corresponding
worksheet cell. Fields the VBA reads but the Python port does not need (Excel
plumbing: LocRowNo, MangRowNo, SoilRowNo, CropColNo, wthRow) have no
counterpart here by design -- a YAML scenario names its files directly.

Sheet -> config mapping, all via `Run` sheet row lookups (iCrop.vba:44-55):
  Location sheet  -> LocationConfig
  Manag sheet     -> ManagementConfig (+ IrrigationSchedule / NitrogenSchedule)
  Soil sheet      -> SoilConfig (+ SoilLayer per layer)
  Crop sheet      -> crop YAML, generated by scripts/extract_crop_params.py
"""

from dataclasses import dataclass, field
from pathlib import Path

import yaml


@dataclass
class LocationConfig:
    """Location sheet, row LocRowNo + 2 (iCrop.vba:51-52, 112-116)."""

    name: str                  # col 1
    latitude: float            # col 2  -- LAT
    vpdf: float                # col 3  -- VPDF: VPD coefficient, NOT a flag.
    #                             Used as `VPD = VPDF * (VPTMAX - VPTMIN)`
    #                             (iCrop.vba:1332); 0.75 is the reference value
    #                             the hourly correction is scaled against
    #                             (iCrop.vba:953).
    temp_change: float         # col 5  -- tchng: climate-change temperature offset (degC)
    precip_change: float       # col 6  -- pchng: precipitation multiplier
    co2: float                 # col 7  -- CO2 (ppm)
    weather_file: str          # col 4  -- wthFile, here a CSV path
    # col 8 (wthRow, first data row in the weather workbook) is Excel plumbing:
    # the CSV loader reads the whole file and indexes by year/DOY instead.


@dataclass
class IrrigationEvent:
    """One scheduled irrigation (iCrop.vba:136-137), Manag row MangRowNo+10+N."""

    time: float                # col 5  -- DAPIR: DAP, CBD or DOY per timing_basis
    amount_mm: float           # col 6  -- IRGWI


@dataclass
class IrrigationSchedule:
    """Only read when water == 3 (iCrop.vba:132-140)."""

    timing_basis: int          # WATiT: 1=DAP-based, 2=CBD-based, 3=DOY-based,
    #                             4=CBD-based with the amount refilling the root
    #                             zone to DUL, amount_mm unused (iCrop.vba:1236-1244)
    events: list[IrrigationEvent] = field(default_factory=list)

    def __post_init__(self) -> None:
        # IRNUM is the VBA's explicit event count; in Python len(events) is it.
        if self.timing_basis not in (1, 2, 3, 4):
            raise ValueError(
                f"irrigation timing_basis must be 1 (DAP), 2 (CBD), 3 (DOY) or "
                f"4 (CBD, automatic amount), got {self.timing_basis}"
            )


@dataclass
class NitrogenEvent:
    """One top-dressing (iCrop.vba:148-150), Manag row MangRowNo+10+N."""

    time: float                # col 2  -- DAPNF: DAP, CBD or DOY per timing_basis
    amount: float              # col 3  -- NFERTI (g N m-2)
    volatilization_fraction: float  # col 4  -- VOLFI


@dataclass
class AutoNitrogen:
    """Automatic N application, wheat only (iCrop.vba:153-161, Manag col 12).

    Reached when NATiT == 4. The VBA flags this section as work-in-progress
    (`<--- ***8989...` at iCrop.vba:153), so treat it as the least-settled part
    of the management inputs.
    """

    ntrsh0: float              # row +11: soil N threshold triggering basal appl.
    nvolf0: float              # row +12: volatilization fraction, basal
    bd_bfrt: float             # row +14: bdBFRT, begin of fertilization window
    bd_tfrt: float             # row +15: bdTFRT, end of fertilization window
    frtwat: float              # row +16: FRTWAT, water needed to apply N
    ntrsh1: float              # row +17: soil N threshold, top-dressing
    napply1: float             # row +18: amount applied per top-dressing
    nvolf1: float              # row +19: volatilization fraction, top-dressing


@dataclass
class NitrogenSchedule:
    """Only read when nitrogen == 2 (iCrop.vba:143-163)."""

    timing_basis: int          # NATiT: 1=DAP, 2=CBD, 3=DOY, 4=automated
    events: list[NitrogenEvent] = field(default_factory=list)
    auto: AutoNitrogen | None = None

    def __post_init__(self) -> None:
        if self.timing_basis in (1, 2, 3):
            if not self.events:
                raise ValueError(
                    f"nitrogen timing_basis={self.timing_basis} needs at least one "
                    f"application event"
                )
        elif self.timing_basis == 4:
            if self.auto is None:
                raise ValueError("nitrogen timing_basis=4 (automated) needs `auto` params")
        else:
            raise ValueError(
                f"nitrogen timing_basis must be 1 (DAP), 2 (CBD), 3 (DOY) or "
                f"4 (automated), got {self.timing_basis}"
            )


@dataclass
class ManagementConfig:
    """Manag sheet (iCrop.vba:53, 67-68, 119-163)."""

    name: str                  # row +2, col 1  -- mngName
    plant_year: int            # row +4, col 2  -- Pyear (first simulated year)
    sim_years: int             # row +4, col 3  -- yrno; Pyear increments per year
    fix_find: int              # row +4, col 1  -- FixFind: sowing algorithm 0-5
    sim_doy: int               # row +4, col 4  -- SimDoy
    pdoy: int                  # row +4, col 5  -- Pdoy: target sowing DOY
    lpdoy: int                 # row +4, col 6  -- Lpdoy: last possible sowing DOY
    stop_doy: int              # row +4, col 7  -- StopDoy (0 = disabled)
    sow_tmp: float             # row +4, col 8  -- SowTmp
    sow_wat: float             # row +4, col 9  -- SowWat
    plant_density: float       # row +4, col 10 -- PDEN (plants m-2)

    water: int                 # row +6, col 6  -- 0=none (potential production),
    #                             1=auto-irrigated, 2=rainfed, 3=scheduled.
    #                             Verified against iCrop.vba:1201-1246.
    #                             SoilWater runs for 1, 2 and 3 (iCrop.vba:85).
    nitrogen: int              # row +6, col 2  -- 0=none, 2=full N balance
    irg_level: float           # row +7, col 7  -- IRGLVL: auto-irrigation trigger

    irrigation: IrrigationSchedule | None = None   # required when water == 3
    nitrogen_schedule: NitrogenSchedule | None = None  # required when nitrogen == 2

    def __post_init__(self) -> None:
        if self.water not in (0, 1, 2, 3):
            raise ValueError(
                f"water must be 0 (none), 1 (auto-irrigated), 2 (rainfed) or "
                f"3 (scheduled), got {self.water}"
            )
        if self.nitrogen not in (0, 2):
            raise ValueError(f"nitrogen must be 0 or 2, got {self.nitrogen}")
        if self.water == 3 and self.irrigation is None:
            raise ValueError("water=3 (scheduled irrigation) needs an `irrigation` block")
        if self.nitrogen == 2 and self.nitrogen_schedule is None:
            raise ValueError("nitrogen=2 needs a `nitrogen_schedule` block")

        # iCrop.vba:122 -- simulation must start at least one day before sowing,
        # silently corrected rather than rejected.
        if self.sim_doy == self.pdoy:
            self.sim_doy = self.pdoy - 1


@dataclass
class SoilLayer:
    """One layer, Soil sheet row SoilRowNo + 6 + L (iCrop.vba:1153-1161, 1580-1586)."""

    depth_mm: float            # col 2  -- DLYER, in MILLIMETRES
    sat: float                 # col 3  -- SAT: saturated water content (mm/mm)
    dul: float                 # col 4  -- DUL: drained upper limit (field capacity)
    cll: float                 # col 5  -- CLL: crop lower limit (wilting point)
    adry: float                # col 6  -- ADRY: air-dry water content
    init_water: float          # col 7  -- WL: initial water content (mm/mm)
    drainf: float              # col 8  -- DRAINF: drainage fraction

    # Read only when nitrogen == 2 (iCrop.vba:1580-1586)
    coarse_fraction: float = 0.0   # col 9  -- FG: fraction soil > 2 mm
    bulk_density: float = 0.0      # col 10 -- BDL (g cm-3)
    organic_n_pct: float = 0.0     # col 11 -- NORGP: organic N (%)
    min_fraction: float = 0.0      # col 12 -- FMIN: org-N fraction mineralizable
    init_no3: float = 0.0          # col 13 -- NSOL1 (kg N ha-1)

    def __post_init__(self) -> None:
        # Physical ordering the tipping-bucket water balance depends on.
        if not (self.adry <= self.cll <= self.dul <= self.sat):
            raise ValueError(
                f"layer water contents must satisfy adry <= cll <= dul <= sat, got "
                f"adry={self.adry}, cll={self.cll}, dul={self.dul}, sat={self.sat}"
            )


@dataclass
class SoilConfig:
    """Soil sheet (iCrop.vba:54, 1138-1141).

    `n_layers` is explicit on purpose. The 2022 source workbook's "Danesh" soil has
    NLYER=5 but *six* filled-in layer rows, and the VBA simulates only the first
    five (`For L = 1 To NLYER`). Deriving the count from len(layers) would
    silently simulate a 6th layer and diverge from VBA.
    """

    name: str                  # row +2, col 1  -- solName
    n_layers: int              # row +4, col 1  -- NLYER
    ldrain: float              # row +4, col 2  -- LDRAIN: layer whose outflow leaves
    #                             the profile as DRAIN (`DRAIN = FLOUT(LDRAIN)`,
    #                             iCrop.vba:1251). A layer number, not a rate.
    salb: float                # row +4, col 3  -- SALB: soil albedo
    cn: float                  # row +4, col 5  -- CN: runoff curve number (sheet label CN2)
    layers: list[SoilLayer] = field(default_factory=list)
    # Row +4 col 4 ("U", stage-1 soil evaporation limit) is present in the sheet
    # but never read by the VBA -- deliberately absent here, not an oversight.

    def __post_init__(self) -> None:
        if not 1 <= self.n_layers <= 10:
            raise ValueError(
                f"n_layers must be 1-10 (VBA ReDim bound, iCrop.vba:59-65), "
                f"got {self.n_layers}"
            )
        if not 0 <= round(self.ldrain) <= 10:
            raise ValueError(
                f"ldrain must be a layer number 0-10 (VBA array bound, "
                f"iCrop.vba:61, 1251), got {self.ldrain}"
            )
        if len(self.layers) < self.n_layers:
            raise ValueError(
                f"n_layers={self.n_layers} but only {len(self.layers)} layers defined"
            )

    @property
    def active_layers(self) -> list[SoilLayer]:
        """The layers the VBA actually simulates (`For L = 1 To NLYER`)."""
        return self.layers[: self.n_layers]


@dataclass
class ScenarioConfig:
    """One row of the Run sheet (iCrop.vba:44-55)."""

    name: str                  # col 1  -- scnName
    location: LocationConfig
    management: ManagementConfig
    soil: SoilConfig
    crop_file: str             # replaces CropColNo: a crop YAML path


def _build_management(raw: dict) -> ManagementConfig:
    irrigation = None
    if (block := raw.pop("irrigation", None)) is not None:
        irrigation = IrrigationSchedule(
            timing_basis=block["timing_basis"],
            events=[IrrigationEvent(**e) for e in block.get("events", [])],
        )

    nitrogen_schedule = None
    if (block := raw.pop("nitrogen_schedule", None)) is not None:
        auto = block.get("auto")
        nitrogen_schedule = NitrogenSchedule(
            timing_basis=block["timing_basis"],
            events=[NitrogenEvent(**e) for e in block.get("events", [])],
            auto=AutoNitrogen(**auto) if auto else None,
        )

    return ManagementConfig(
        **raw, irrigation=irrigation, nitrogen_schedule=nitrogen_schedule
    )


def load_scenario(path: str | Path) -> ScenarioConfig:
    """Load a scenario YAML.

    `weather_file` and `crop_file` are resolved relative to the scenario file's
    own directory, so a scenario is portable and does not depend on the process
    working directory. Absolute paths are used as given.
    """
    path = Path(path).resolve()
    with path.open() as fh:
        raw = yaml.safe_load(fh)

    def resolve(ref: str) -> str:
        candidate = Path(ref)
        return str(candidate if candidate.is_absolute() else (path.parent / candidate))

    soil_raw = raw["soil"]
    soil = SoilConfig(
        name=soil_raw["name"],
        n_layers=soil_raw["n_layers"],
        ldrain=soil_raw["ldrain"],
        salb=soil_raw["salb"],
        cn=soil_raw["cn"],
        layers=[SoilLayer(**layer) for layer in soil_raw["layers"]],
    )

    location_raw = dict(raw["location"])
    location_raw["weather_file"] = resolve(location_raw["weather_file"])

    return ScenarioConfig(
        name=raw["name"],
        location=LocationConfig(**location_raw),
        management=_build_management(dict(raw["management"])),
        soil=soil,
        crop_file=resolve(raw["crop_file"]),
    )


def load_crop_params(path: str | Path) -> dict:
    """Load a crop YAML as generated by scripts/extract_crop_params.py.

    Returns the raw nested dict (`phenology`, `lai`, `dm_production`,
    `dm_distribution`); building the per-module params dataclasses from it is the
    caller's job, since each module owns its own parameter type.
    """
    with Path(path).open() as fh:
        return yaml.safe_load(fh)
