"""Extract one soil from a source workbook's Soil sheet into YAML.

The default is the 2022 source workbook, the version the port targets; its Soil
sheet is identical to the verification workbook's.

The Soil sheet stores one soil per block. A block starts at the row the Run
sheet calls SoilRowNo (marked "<-- SoilRowNo" in column A); the cells VBA reads
are offsets from it:

    SoilRowNo + 2, col 1        soil name                  (iCrop.vba:54)
    SoilRowNo + 4, cols 1-3, 5  NLYER, LDRAIN, SALB, CN2   (iCrop.vba:1138-1141)
    SoilRowNo + 6 + L           layer L                    (iCrop.vba:1153-1161, 1580-1587)

Column 4 of the SoilRowNo + 4 row ("U") is not read by iCrop.vba.

Why a script and not hand-transcription: the sheet shows rounded values, but
stores the doubles they were computed from, e.g. LL = 0.20400000000000001
instead of 0.204. VBA reads the stored double, so only the extracted value
reproduces the reference output exactly.

Every filled layer row is emitted, including rows beyond NLYER ("Danesh" has
six filled rows and NLYER = 5). VBA reads only the first NLYER rows, and so does
the port: `n_layers` is explicit, never the length of `layers`.

Usage:
    .venv/bin/python scripts/extract_soil_params.py --list
    .venv/bin/python scripts/extract_soil_params.py --row 24 -o configs/soils/danesh.yaml
"""

import argparse
from pathlib import Path

import openpyxl
import yaml

REPO_ROOT = Path(__file__).parent.parent
WORKBOOK = REPO_ROOT / "SSM-iCrop" / "SSM_iCrop__2022_05_29.xlsm"
MARKER = "<-- SoilRowNo"
MAX_LAYERS = 10  # the sheet has ten layer rows per block

# yaml key -> (column on row SoilRowNo + 4, iCrop.vba line that reads it)
SOIL_COLUMNS = {
    "n_layers": (1, 1138),  # NLYER
    "ldrain": (2, 1139),    # LDRAIN
    "salb": (3, 1140),      # SALB
    "cn": (5, 1141),        # CN2
}

# yaml key -> (column on row SoilRowNo + 6 + L, iCrop.vba line that reads it)
LAYER_COLUMNS = {
    "depth_mm": (2, 1153),         # DLYER, mm
    "sat": (3, 1154),              # SAT
    "dul": (4, 1155),              # DUL
    "cll": (5, 1156),              # CLL (sheet label "LL")
    "adry": (6, 1158),             # ADRY
    "init_water": (7, 1159),       # WL, mm/mm before * DLYER at :1160
    "drainf": (8, 1161),           # DRAINF
    "coarse_fraction": (9, 1580),  # FG
    "bulk_density": (10, 1581),    # BDL
    "organic_n_pct": (11, 1582),   # NORGP
    "min_fraction": (12, 1583),    # FMIN
    "init_no3": (13, 1586),        # NSOL1, kg N ha-1
}


def _number(ws, row: int, column: int, key: str, vba_line: int) -> float:
    """Read a numeric cell; a blank reads as 0, as in VBA."""
    value = ws.cell(row, column).value
    if value is None:
        return 0.0
    if not isinstance(value, (int, float)):
        raise SystemExit(
            f"row {row}, column {column} ({key}, iCrop.vba:{vba_line}) holds "
            f"{value!r}, not a number"
        )
    return float(value)


def soil_rows(ws) -> list[int]:
    """Rows that start a soil block."""
    return [
        row for row in range(1, ws.max_row + 1)
        if str(ws.cell(row, 1).value or "").strip() == MARKER
    ]


def extract(workbook: Path, soil_row: int) -> dict:
    ws = openpyxl.load_workbook(workbook, data_only=True)["Soil"]
    if str(ws.cell(soil_row, 1).value or "").strip() != MARKER:
        raise SystemExit(f"row {soil_row} does not start a soil block ({MARKER!r})")

    name = ws.cell(soil_row + 2, 1).value
    soil = {
        key: _number(ws, soil_row + 4, column, key, line)
        for key, (column, line) in SOIL_COLUMNS.items()
    }
    soil["n_layers"] = int(soil["n_layers"])

    layers = []
    for layer in range(1, MAX_LAYERS + 1):
        row = soil_row + 6 + layer
        if ws.cell(row, LAYER_COLUMNS["depth_mm"][0]).value is None:
            break  # first unfilled layer row ends the profile
        layers.append({
            key: _number(ws, row, column, key, line)
            for key, (column, line) in LAYER_COLUMNS.items()
        })

    if len(layers) < soil["n_layers"]:
        raise SystemExit(
            f"soil {name!r} has NLYER = {soil['n_layers']} but only "
            f"{len(layers)} filled layer rows"
        )

    return {
        "_source": {
            "workbook": str(workbook.relative_to(REPO_ROOT)),
            "sheet": "Soil",
            "soil_row": soil_row,
            "note": (
                "Generated by scripts/extract_soil_params.py -- do not hand-edit. "
                "Layers beyond n_layers are in the sheet but not simulated."
            ),
        },
        "name": str(name).strip(),
        **soil,
        "layers": layers,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--row", type=int, default=24,
                    help="SoilRowNo of the block (default: 24 = Danesh)")
    ap.add_argument("-o", "--output", type=Path, help="write YAML here (default: stdout)")
    ap.add_argument("--workbook", type=Path, default=WORKBOOK)
    ap.add_argument("--list", action="store_true", help="list soils and exit")
    args = ap.parse_args()

    if args.list:
        ws = openpyxl.load_workbook(args.workbook, data_only=True)["Soil"]
        for row in soil_rows(ws):
            print(f"{row:>4}  {ws.cell(row + 2, 1).value}")
        return

    params = extract(args.workbook.resolve(), args.row)
    text = yaml.safe_dump(params, sort_keys=False, default_flow_style=False)

    if args.output:
        args.output.write_text(text)
        print(f"wrote {args.output} ({params['name']}, row {args.row})")
    else:
        print(text)


if __name__ == "__main__":
    main()
